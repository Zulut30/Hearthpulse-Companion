"""Generate the .agents/skills stubs that let Codex find the project skills kept in .claude/skills.

Codex scans .agents/skills (from the working directory up to the repository root), not .claude/skills. Each project
skill gets a stub there with the same `name` and `description` and a body that sends the agent to the real file, so a
skill's text lives in one place. A skill with `disable-model-invocation: true` also gets `agents/openai.yaml` with
`allow_implicit_invocation: false`: Codex then runs it only when it is named ($skill), as Claude Code does.

Run from the repository root after adding, renaming, deleting a skill or editing a description:
    python tools/skills/gen_codex_stubs.py           # rewrite .agents/skills
    python tools/skills/gen_codex_stubs.py --check   # exit 1 when the stubs differ from the skills

tools/skill_checks/test_codex_stubs.py runs the same comparison in CI.
"""
import shutil
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[2]
SOURCE = ROOT / ".claude/skills"
STUBS = ROOT / ".agents/skills"

BODY = """\
Open `.claude/skills/{name}/SKILL.md` (path from the repository root) and follow it. Relative links in it resolve
from its own folder, `.claude/skills/{name}/`.

Generated by `tools/skills/gen_codex_stubs.py` from that file: edit the skill there, then rerun the script.
"""

OWNER_INVOKED = """\
# Generated by tools/skills/gen_codex_stubs.py: the source skill sets disable-model-invocation.
policy:
  allow_implicit_invocation: false
"""


def frontmatter(skill_md):
    """The YAML frontmatter of a SKILL.md as a dict."""
    text = skill_md.read_text(encoding="utf-8")
    if not text.startswith("---\n"):
        raise ValueError(f"{skill_md}: no YAML frontmatter")
    return yaml.safe_load(text.split("---", 2)[1])


def expected(source=SOURCE):
    """Every file .agents/skills must hold: {path relative to it (posix): text}."""
    files = {}
    for skill_md in sorted(source.glob("*/SKILL.md")):
        front = frontmatter(skill_md)
        name = skill_md.parent.name
        head = yaml.safe_dump({"name": front["name"], "description": front["description"]},
                              allow_unicode=True, sort_keys=False, width=float("inf"))
        files[f"{name}/SKILL.md"] = f"---\n{head}---\n\n{BODY.format(name=name)}"
        if front.get("disable-model-invocation") is True:
            files[f"{name}/agents/openai.yaml"] = OWNER_INVOKED
    return files


def actual(stubs=STUBS):
    """What .agents/skills holds now, in the same shape."""
    if not stubs.is_dir():
        return {}
    return {path.relative_to(stubs).as_posix(): path.read_text(encoding="utf-8")
            for path in sorted(stubs.rglob("*")) if path.is_file()}


def differences(source=SOURCE, stubs=STUBS):
    """Human-readable lines, empty when the stubs match the skills."""
    want, have = expected(source), actual(stubs)
    return ([f"missing: {path}" for path in sorted(want.keys() - have.keys())]
            + [f"not generated from a skill: {path}" for path in sorted(have.keys() - want.keys())]
            + [f"out of date: {path}" for path in sorted(want.keys() & have.keys()) if want[path] != have[path]])


def write(source=SOURCE, stubs=STUBS):
    """Replace the stubs folder with the expected files."""
    if stubs.is_dir():
        shutil.rmtree(stubs)
    for relative, text in expected(source).items():
        path = stubs / relative
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding="utf-8", newline="\n")


def main(argv):
    if "--check" in argv:
        found = differences()
        for line in found:
            print(line)
        if found:
            print("Run: python tools/skills/gen_codex_stubs.py")
        return 1 if found else 0
    write()
    print(f"{len(expected())} files in {STUBS.relative_to(ROOT).as_posix()}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
