#!/usr/bin/env python3
"""Generates src/Hearthpulse.Core/Battlegrounds/Effects/deaths/BattlecryPool.g.cs.

Brann's Epic Egg (TB_BaconShop_HERO_43_Buddy): "Deathrattle: Summon and get a random Battlecry minion." (golden: 2). The
simulator needs the public list of minions it can summon. This script takes them from a card data snapshot of the current patch
(tools/effects/fetch_bg_data.py):

  every minion of the Tavern pool (Hearthpulse data API v1 `in_pool`, else HearthstoneJSON's pool flag) whose
  HearthstoneJSON mechanics include BATTLECRY, except the Duos-only minions,

with its printed (normal) Attack, Health, tribes, keywords and tier from HearthstoneJSON.

Usage (isolated interpreter, the snapshot folder passed as an argument):
  python3 -I tools/effects/gen_battlecry_pool.py <snapshot> src/Hearthpulse.Core/Battlegrounds/Effects/deaths/BattlecryPool.g.cs
"""
import pathlib
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
from bgdata import KEYWORDS, MECHANICS, TRIBES, Snapshot, flags  # noqa: E402

def main(source, output):
    data = Snapshot(source)
    rows = []
    for card, duos in data.pool_minions():
        mechanics = card.get("mechanics") or []
        if "BATTLECRY" not in mechanics or duos:
            continue
        rows.append((card.get("techLevel") or 0, card["id"], card.get("name", ""), card.get("attack") or 0, card.get("health") or 0,
                     flags(card.get("races") or [], TRIBES, "Tribe.None"), flags(mechanics, KEYWORDS, "Keyword.None"),
                     flags(mechanics, MECHANICS, "CardMechanic.None")))
    rows.sort()

    lines = [
        "// <auto-generated>",
        "// Generated by tools/effects/gen_battlecry_pool.py from a card data snapshot (tools/effects/fetch_bg_data.py):",
        f"// {data.source}.",
        "// Do not edit by hand: regenerate after a patch.",
        "// </auto-generated>",
        "namespace Hearthpulse.Core.Battlegrounds.Effects.Deaths;",
        "",
        "internal static partial class BattlecryPool",
        "{",
        f"    public const string Patch = \"{data.patch}\";",
        "",
        "    /// <summary>Pool minions with a Battlecry (not Duos-only), by tier then card id: printed normal stats.</summary>",
        "    private static readonly SimMinion[] Generated =",
        "    [",
    ]
    for tier, card_id, name, atk, hp, tribe, keywords, mechanics in rows:
        lines.append(f"        M(\"{card_id}\", {atk}, {hp}, {tier}, {tribe}, {keywords}, {mechanics}), // {name}")
    lines += ["    ];", "}", ""]

    with open(output, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines))
    print(f"{len(rows)} minions -> {output}")


if __name__ == "__main__":
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    main(sys.argv[1], sys.argv[2])
