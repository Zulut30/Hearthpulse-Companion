#!/usr/bin/env python3
"""Generates src/Hearthpulse.Core/Battlegrounds/Effects/ongoing/UndeadPool.g.cs.

Deathly Striker (BG31_835): "Avenge (4): Get a random Undead. Deathrattle: Summon it from your hand for this combat
only." (golden: 2). The simulator needs the public list of Undead it can get. This script takes them from a card data
snapshot of the current patch (tools/effects/fetch_bg_data.py):

  every minion of the Tavern pool (Hearthpulse data API v1 `in_pool`, else HearthstoneJSON's pool flag) whose
  HearthstoneJSON types include UNDEAD or ALL, except Dark Paradox (its type, stats and tier change every game) and
  the Duos-only minions,

with its printed (normal) Attack, Health, tribes, keywords, mechanics and tier from HearthstoneJSON.

Usage (isolated interpreter, the snapshot folder passed as an argument):
  python3 -I tools/effects/gen_undead_pool.py <snapshot> src/Hearthpulse.Core/Battlegrounds/Effects/ongoing/UndeadPool.g.cs
"""
import pathlib
import re
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
from bgdata import KEYWORDS, MECHANICS, TRIBES, Snapshot, flags  # noqa: E402

EXCLUDED = {"BG36_360"}  # Dark Paradox


def main(source, target):
    data = Snapshot(source)
    rows = []
    for card, duos in data.pool_minions():
        tribes = card.get("races") or []
        if card["id"] in EXCLUDED or duos or ("UNDEAD" not in tribes and "ALL" not in tribes):
            continue
        rows.append((card.get("techLevel") or 0, card["id"], card))

    rows.sort(key=lambda r: (r[0], r[1]))
    lines = []
    for tier, card_id, card in rows:
        mechanics = card.get("mechanics") or []
        name = re.sub(r"[\r\n]", " ", card.get("name", ""))
        lines.append(
            f'        M("{card_id}", {card.get("attack") or 0}, {card.get("health") or 0}, {tier}, '
            f'{flags(card.get("races") or [], TRIBES, "Tribe.None")}, {flags(mechanics, KEYWORDS, "Keyword.None")}, '
            f'{flags(mechanics, MECHANICS, "CardMechanic.None")}), // {name}'
        )

    body = "\n".join(lines)
    text = f"""// <auto-generated>
// Generated by tools/effects/gen_undead_pool.py from a card data snapshot (tools/effects/fetch_bg_data.py):
// {data.source}.
// Do not edit by hand: regenerate after a patch.
// </auto-generated>
namespace Hearthpulse.Core.Battlegrounds.Effects.Ongoing;

internal static partial class UndeadPool
{{
    public const string Patch = "{data.patch}";

    /// <summary>Undead (and all-type) pool minions, not Duos-only, by tier then card id: printed normal stats.</summary>
    private static readonly SimMinion[] Generated =
    [
{body}
    ];
}}
"""
    with open(target, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    print(f"{len(rows)} minions -> {target}")


if __name__ == "__main__":
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    main(sys.argv[1], sys.argv[2])
